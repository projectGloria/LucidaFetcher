// Regenerates src/ui/brand-icons.js from simple-icons.
//
// The icons are baked into a source file rather than imported at runtime for
// two reasons: simple-icons is a 3,400-icon dev dependency that has no business
// in the shipped bundle, and the file is then readable - you can see exactly
// which mark the app draws for a source without running it.
//
// Icon path data from simple-icons is CC0; the trademarks belong to their
// owners and are used here only to identify the service being searched.
//
//   node scripts/gen-brand-icons.mjs
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

// service id -> simple-icons export. Anything not listed here has no official
// mark in simple-icons (Amazon's are absent entirely, Qobuz and Yandex Music
// have never been added) and falls back to a lettermark in brand-icons.js.
const OFFICIAL = {
  soundcloud: 'siSoundcloud',
  youtube: 'siYoutube',
  spotify: 'siSpotify',
  deezer: 'siDeezer',
  tidal: 'siTidal',
  napster: 'siNapster',
};

const rows = Object.entries(OFFICIAL).map(([service, key]) => {
  const icon = si[key];
  if (!icon) throw new Error(`simple-icons has no ${key} (for ${service})`);
  return `  ${service}: { title: ${JSON.stringify(icon.title)}, hex: '#${icon.hex}', path: '${icon.path}' },`;
});

writeFileSync(new URL('../src/ui/brand-icons.js', import.meta.url), `// GENERATED by scripts/gen-brand-icons.mjs - do not edit by hand.
//
// Official brand marks, as 24x24 SVG path data from simple-icons (path data is
// CC0; the trademarks belong to their owners and appear here only to identify
// which service the app is talking to). simple-icons ${si.siSoundcloud ? '' : ''}stays a dev dependency: baking
// the six marks the app can actually show beats bundling three thousand.

export const BRAND_ICONS = {
${rows.join('\n')}
};
`);
console.log(`wrote ${rows.length} brand icons`);
