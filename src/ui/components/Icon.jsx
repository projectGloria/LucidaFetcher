/**
 * `<Icon name="pause" />` - decorative by default (aria-hidden), because nearly
 * every icon here sits inside a button that already carries a title or text.
 * Pass `label` for the rare icon that is the only thing saying what it means.
 */
export default function Icon({ name, size = 16, label, className = '', strokeWidth = 2 }) {
  const shape = PATHS[name];
  if (!shape) return null;
  // play/pause read as solid glyphs at small sizes; outlined they look hollow
  // and lighter than every other control on the bar.
  const solid = name === 'play' || name === 'pause' || name === 'zap';
  return (
    <svg
      className={`icon ${className}`}
      width={size} height={size} viewBox="0 0 24 24"
      fill={solid ? 'currentColor' : 'none'}
      stroke="currentColor" strokeWidth={solid ? 0 : strokeWidth}
      strokeLinecap="round" strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? 'img' : undefined}
      aria-label={label}
      focusable="false"
    >
      {shape}
    </svg>
  );
}
